def find_route(origin: str, destination: str):
    """উৎস ও গন্তব্য দিয়ে রুট খোঁজে"""
    o = origin.strip().lower()
    d = destination.strip().lower()

    for area, routes in BUS_ROUTES.items():
        if o in area.lower() or area.lower() in o:
            for dest, info in routes.items():
                if d in dest.lower() or dest.lower() in d:
                    return info

